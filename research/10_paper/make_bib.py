"""Build references.bib for the [Pnnn] keys cited in R1_draft.md from 02_screening/final_papers.csv (verified metadata only).
arXiv-only works cited inline get @misc entries with their eprint id; their titles are left for verification, not guessed.
Run: /usr/bin/python3 -I -B make_bib.py"""
import csv, re
from pathlib import Path

H = Path(__file__).resolve().parent; R = H.parent
draft = (H / 'R1_draft.md').read_text()
keys = sorted(set(re.findall(r'P\d{3}', ' '.join(re.findall(r'\[P\d{3}[^\]]*\]', draft)))))
rows = {r['final_id']: r for r in csv.DictReader(open(R / '02_screening/final_papers.csv', newline='', encoding='utf-8'))}


def esc(s):
    return s.replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def authors(s):
    parts = [a.strip() for a in re.split(r';|\s+and\s+|,\s*(?=[A-Z][^,]*\s[A-Z])', s) if a.strip()]
    return ' and '.join(parts) if parts else s


out = []
for k in keys:
    r = rows[k]; v = r['venue']; t = (r['publication_type'] or '').lower()
    vl = v.lower()
    if vl.strip() in ('', 'arxiv') or 'preprint' in vl: kind = 'misc'
    elif vl.startswith('proceedings of the acm on'): kind = 'article'          # PACM journals (PACMPL, PACMSE)
    elif any(w in vl for w in ('proceed', 'conference', 'symposium')) or 'proceedings' in t: kind = 'inproceedings'
    else: kind = 'article'
    f = {'title': '{' + esc(r['title']) + '}', 'author': esc(authors(r['authors'])), 'year': r['year']}
    if kind == 'inproceedings': f['booktitle'] = esc(v)
    elif kind == 'article': f['journal'] = esc(v)
    else: f['howpublished'] = 'Preprint'
    doi = r['doi'].replace('https://doi.org/', '').strip()
    if doi.startswith('10.'): f['doi'] = doi
    if re.fullmatch(r'\d{4}\.\d{4,5}(v\d+)?', r['arxiv_id'].strip()): f['eprint'] = r['arxiv_id']; f['archivePrefix'] = 'arXiv'
    if r['canonical_url'] and not r['doi']: f['url'] = r['canonical_url']
    if r['needs_verification'].strip().lower() in ('yes', 'true', 'y'): f['note'] = 'metadata flagged for verification in final_papers.csv'
    out.append(f'@{kind}{{{k},\n' + ',\n'.join(f'  {a} = {{{b}}}' for a, b in f.items()) + '\n}\n')
# arXiv-only works cited inline; metadata verified from the arXiv abstract pages on 2026-11-17 (v1 for all three)
ARXIV = {
    '2607.12101': ('Fault Injection in OpenAPI Specifications for Evaluating Black-Box Testing Effectiveness',
                   'Hamza Bin Mazhar and Yuqing Wang and Mika V. M{\\"a}ntyl{\\"a}', '2026'),
    '2512.08706': ('RESTifAI: LLM-Based Workflow for Reusable REST API Testing',
                   'Leon Kogler and Maximilian Ehrhart and Benedikt Dornauer and Eduard Paul Enoiu', '2025'),
    '2609.27806': ('DualMine: Static-Dynamic REST API Constraint Discovery with Dual Validation',
                   'Tu Nguyen and Huy Nguyen and Juan C. A. Valenzuela and Thanh Nguyen and Tien N. Nguyen and Vu Nguyen', '2026'),
}
for eid in sorted(set(re.findall(r'arXiv (\d{4}\.\d{4,5})', draft))):
    if eid in ARXIV:
        t, a, y = ARXIV[eid]
        out.append(f'@misc{{arXiv{eid.replace(".", "_")},\n  title = {{{{{esc(t)}}}}},\n  author = {{{a}}},\n  year = {{{y}}},\n  howpublished = {{Preprint}},\n  eprint = {{{eid}}},\n  archivePrefix = {{arXiv}}\n}}\n')
    else:
        out.append(f'@misc{{arXiv{eid.replace(".", "_")},\n  eprint = {{{eid}}},\n  archivePrefix = {{arXiv}},\n  title = {{[verify title and authors from arXiv {eid}]}}\n}}\n')
(H / 'references.bib').write_text('% Generated by make_bib.py from 02_screening/final_papers.csv; do not edit by hand.\n\n' + '\n'.join(out))
print(len(keys), 'P keys +', len(out) - len(keys), 'arXiv entries ->', H / 'references.bib')
